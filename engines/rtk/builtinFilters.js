// matchRtkFilter 等价逻辑：按 priority 排序后查找第一个匹配
// （上游按 source > format > priority > id 排序，这里全是 builtin/omniroute-json）
export function matchRtkFilter(text, command) {
  // 上游 filterLoader.ts matchRtkFilter：先 detectCommandType，再按优先级降序
  // 依次尝试 commandTypes.includes(detection.type) → commandPatterns → matchPatterns。
  // 移植差异：无 project/global/TOML 源（builtin-only），排序 = priority desc, id asc。
  const detection = detectCommandType(text, command)
  const detectedCommand = detection.command ?? command ?? ""
  const sorted = [...BUILTIN_FILTERS].sort(
    (a, b) => b.priority - a.priority || a.id.localeCompare(b.id)
  )
  const matched =
    sorted.find((f) => f.commandTypes.includes(detection.type)) ??
    sorted.find(
      (f) =>
        detectedCommand &&
        f.commandPatterns.some((p) => {
          try { return new RegExp(p, "i").test(detectedCommand) } catch { return false }
        })
    ) ??
    sorted.find((f) =>
      f.matchPatterns.some((p) => {
        try { return new RegExp(p, "im").test(text) } catch { return false }
      })
    )
  if (matched) return matched
  return sorted.find((f) => f.commandTypes.includes("generic-output")) ?? null
}
